import re
import shutil
import sys
from pathlib import Path

from config import AGENTS_DIR, PROFILES_DIR

ADK_NAME = re.compile(r"[a-zA-Z0-9_]+")
MARKER = "# Generated by sync_agents.py; do not edit."
LEGACY_MARKERS = {"# Generated by scripts/sync-agents.py; do not edit."}
GENERATED_MARKERS = {MARKER} | LEGACY_MARKERS

SHIM = """{marker}
from factory import create_app

app = create_app({profile!r})
"""


def sync_agents() -> None:
    AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    wanted: dict[str, str | None] = {"bot": None}
    if PROFILES_DIR.is_dir():
        for entry in sorted(PROFILES_DIR.iterdir()):
            if not entry.is_dir():
                continue
            name = entry.name
            if not ADK_NAME.fullmatch(name):
                print(
                    f"warning: skipping profile {name!r}: ADK agent names may only contain letters, digits and underscores",
                    file=sys.stderr,
                )
                continue
            wanted[name] = name
    to_write: list[tuple[Path, str]] = []
    for name, profile in wanted.items():
        content = SHIM.format(marker=MARKER, profile=profile)
        shim = AGENTS_DIR / name / "agent.py"
        try:
            if shim.read_text(encoding="utf-8") == content:
                continue
        except OSError:
            pass
        to_write.append((shim, content))
    to_remove: list[Path] = []
    for entry in sorted(AGENTS_DIR.iterdir()):
        if not entry.is_dir() or entry.name in wanted:
            continue
        shim = entry / "agent.py"
        try:
            first_line = shim.read_text(encoding="utf-8").splitlines()[0]
        except (OSError, IndexError):
            continue
        if first_line in GENERATED_MARKERS:
            to_remove.append(entry)
    if not to_write and not to_remove:
        print("Shims are up to date")
        return
    print("Creating shims...")
    for shim, content in to_write:
        shim.parent.mkdir(exist_ok=True)
        shim.write_text(content, encoding="utf-8")
    for entry in to_remove:
        shutil.rmtree(entry)


def main() -> None:
    sync_agents()


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
AGENTS_DIR = Path.home() / ".bots" / "agents"
PROFILES_DIR = Path.home() / ".bots" / "profiles"
ADK_NAME = re.compile(r"[a-zA-Z0-9_]+")
MARKER = "# Generated by scripts/sync-agents.py; do not edit."

SHIM = """{marker}
import sys
from pathlib import Path

REPO = Path({repo!r})
sys.path.insert(0, str(REPO))

from factory import create_app

app = create_app({profile!r})
"""


def main() -> None:
    AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    wanted: dict[str, str | None] = {"bot": None}
    if PROFILES_DIR.is_dir():
        for entry in sorted(PROFILES_DIR.iterdir()):
            if not entry.is_dir():
                continue
            name = entry.name
            if not ADK_NAME.fullmatch(name):
                print(
                    f"warning: skipping profile {name!r}: ADK agent names may only contain letters, digits and underscores",
                    file=sys.stderr,
                )
                continue
            wanted[name] = name
    for name, profile in wanted.items():
        target = AGENTS_DIR / name
        target.mkdir(exist_ok=True)
        shim = target / "agent.py"
        shim.write_text(SHIM.format(marker=MARKER, repo=str(REPO), profile=profile), encoding="utf-8")
        print(f"wrote {shim}")
    for entry in sorted(AGENTS_DIR.iterdir()):
        if not entry.is_dir() or entry.name in wanted:
            continue
        shim = entry / "agent.py"
        try:
            first_line = shim.read_text(encoding="utf-8").splitlines()[0]
        except (OSError, IndexError):
            continue
        if first_line != MARKER:
            continue
        for child in entry.iterdir():
            child.unlink()
        entry.rmdir()
        print(f"removed stale shim {entry}")


if __name__ == "__main__":
    main()
